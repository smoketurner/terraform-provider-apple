package apispec

import (
	"errors"
	"fmt"
	"strings"
)

// GeneratorConfig returns the oapi-codegen configuration for the client in
// internal/asc/gen, which includes only the operations in m.Generated(). The
// overlay renames Go types whose default names collide, and enum constants
// always carry their type's name, e.g. CapabilitySettingKeyICLOUDVERSION.
// date-time strings decode into DateTime (internal/asc/gen/datetime.go),
// because Apple's offsets are not RFC 3339. It fails when no
// operation is generated, because oapi-codegen reads an empty
// include-operation-ids as "every operation".
func GeneratorConfig(m *Manifest) ([]byte, error) {
	ids := m.Generated()
	if len(ids) == 0 {
		return nil, errors.New("coverage.yaml marks no operation covered or in_progress")
	}
	var b strings.Builder
	b.WriteString(`# Code generated by "apispec gencfg" from coverage.yaml. DO NOT EDIT.
package: gen
generate:
  models: true
  client: true
  std-http-server: true
compatibility:
  always-prefix-enum-values: true
output-options:
  resolve-type-name-collisions: true
  type-mapping:
    string:
      formats:
        date-time:
          type: DateTime
  overlay:
    path: overlay.yaml
  include-operation-ids:
`)
	for _, id := range ids {
		fmt.Fprintf(&b, "    - %s\n", id)
	}
	return []byte(b.String()), nil
}
