// inlinePrices returns the relationship data and inline objects of offer
// prices of type typ, referenced by local IDs.
func inlinePrices(prices []offerPriceModel, typ string) (refs, included []map[string]any) {
	refs, included = []map[string]any{}, []map[string]any{}
	for i, p := range prices {
		local := fmt.Sprintf("${price-%d}", i)
		refs = append(refs, map[string]any{"type": typ, "id": local})
		included = append(included, map[string]any{"type": typ, "id": local, "relationships": map[string]any{
			"territory":              map[string]any{"data": map[string]string{"type": "territories", "id": p.Territory.ValueString()}},
			"subscriptionPricePoint": map[string]any{"data": map[string]string{"type": "subscriptionPricePoints", "id": p.PricePointID.ValueString()}},
		}})
	}
	return refs, included
}

func offerPriceModels[T any](items []T, territory, point func(T) string) []offerPriceModel {
	out := []offerPriceModel{}
	for _, p := range items {
		out = append(out, offerPriceModel{Territory: types.StringValue(territory(p)), PricePointID: types.StringValue(point(p))})
	}
	return out
}

