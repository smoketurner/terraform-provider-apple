const offerModeDoc = "`FREE_TRIAL`, `PAY_AS_YOU_GO` (a discounted price each period) or `PAY_UP_FRONT` (one discounted price for all periods)"

func replacedInt(desc string, validators ...validator.Int64) schema.Int64Attribute {
	return schema.Int64Attribute{MarkdownDescription: desc, Required: true, Validators: validators, PlanModifiers: []planmodifier.Int64{int64planmodifier.RequiresReplace()}}
}

func replacedPlanType() schema.StringAttribute {
	return schema.StringAttribute{
		MarkdownDescription: "Plan the offer is for: " + planTypeDoc + ". Defaults to `UPFRONT`.",
		Optional:            true,
		Computed:            true,
		Validators:          []validator.String{oneOf(planTypes)},
		PlanModifiers:       []planmodifier.String{stringplanmodifier.RequiresReplace(), stringplanmodifier.UseStateForUnknown()},
	}
}

